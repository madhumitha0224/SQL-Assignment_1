SELECT 
    l.FULL_NAME,
    c.COURSE_NAME,
    c.CATEGORY,
    p.QUANTITY,
    ROUND(c.UNIT_PRICE * p.QUANTITY, 2) AS total_amount,
    p.PURCHASE_DATE
FROM 
    LEARNERS l
INNER JOIN 
    PURCHASES p ON l.LEARNER_ID = p.LEARNER_ID
INNER JOIN 
    COURSES c ON p.COURSE_ID = c.COURSE_ID
ORDER BY 
    total_amount DESC;
    
    SELECT 
    l.FULL_NAME,
    c.COURSE_NAME,
    c.CATEGORY,
    p.QUANTITY,
    ROUND(c.UNIT_PRICE * p.QUANTITY, 2) AS total_amount,
    p.PURCHASE_DATE
FROM 
    LEARNERS l
LEFT JOIN 
    PURCHASES p ON l.LEARNER_ID = p.LEARNER_ID
LEFT JOIN 
    COURSES c ON p.COURSE_ID = c.COURSE_ID
ORDER BY 
    total_amount DESC;
    
    SELECT 
    l.FULL_NAME,
    c.COURSE_NAME,
    c.CATEGORY,
    p.QUANTITY,
    ROUND(c.UNIT_PRICE * p.QUANTITY, 2) AS total_amount,
    p.PURCHASE_DATE
FROM 
    LEARNERS l
RIGHT JOIN 
    PURCHASES p ON l.LEARNER_ID = p.LEARNER_ID
RIGHT JOIN 
    COURSES c ON p.COURSE_ID = c.COURSE_ID
ORDER BY 
    total_amount DESC;
    
    SELECT 
    l.FULL_NAME,
    l.COUNTRY,
    ROUND(SUM(c.UNIT_PRICE * p.QUANTITY), 2) AS total_spending
FROM 
    LEARNERS l
JOIN 
    PURCHASES p ON l.LEARNER_ID = p.LEARNER_ID
JOIN 
    COURSES c ON p.COURSE_ID = c.COURSE_ID
GROUP BY 
    l.LEARNER_ID, l.FULL_NAME, l.COUNTRY
ORDER BY 
    total_spending DESC;
    
    SELECT 
    c.COURSE_NAME,
    SUM(p.QUANTITY) AS total_quantity_sold
FROM 
    COURSES c
JOIN 
    PURCHASES p ON c.COURSE_ID = p.COURSE_ID
GROUP BY 
    c.COURSE_ID, c.COURSE_NAME
ORDER BY 
    total_quantity_sold DESC
LIMIT 3;

SELECT 
    c.CATEGORY,
    ROUND(SUM(c.UNIT_PRICE * p.QUANTITY), 2) AS total_revenue,
    COUNT(DISTINCT p.LEARNER_ID) AS unique_learners_count
FROM 
    COURSES c
JOIN 
    PURCHASES p ON c.COURSE_ID = p.COURSE_ID
GROUP BY 
    c.CATEGORY
ORDER BY 
    total_revenue DESC;
    
    SELECT 
    l.FULL_NAME,
    COUNT(DISTINCT c.CATEGORY) AS category_count
FROM 
    LEARNERS l
JOIN 
    PURCHASES p ON l.LEARNER_ID = p.LEARNER_ID
JOIN 
    COURSES c ON p.COURSE_ID = c.COURSE_ID
GROUP BY 
    l.LEARNER_ID, l.FULL_NAME
HAVING 
    COUNT(DISTINCT c.CATEGORY) > 1;
    
    SELECT 
    c.COURSE_NAME,
    c.CATEGORY,
    c.UNIT_PRICE
FROM 
    COURSES c
LEFT JOIN 
    PURCHASES p ON c.COURSE_ID = p.COURSE_ID
WHERE 
    p.PURCHASE_ID IS NULL;